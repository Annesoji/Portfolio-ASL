document.addEventListener('DOMContentLoaded', () => {
    // --- Break Inception Loop if loaded inside Iframe ---
    if (window.self !== window.top) {
        document.body.classList.add('in-iframe');
        const heroVisual = document.querySelector('.hero-visual');
        if (heroVisual) heroVisual.style.display = 'none';
        
        // Disable custom cursor tracking inside iframe to avoid duplicate double cursors and lag
        const trackCursor = document.querySelector('.glass-cursor');
        if (trackCursor) trackCursor.style.display = 'none';
    }

    // --- Language Toggle Logic ---
    const langToggleBtn = document.getElementById('lang-switch');
    if (langToggleBtn) {
        langToggleBtn.addEventListener('change', (e) => {
            const newLang = e.target.checked ? 'fr' : 'en';
            document.documentElement.lang = newLang; // set HTML lang attribute
            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (translations[newLang] && translations[newLang][key]) {
                    el.innerHTML = translations[newLang][key];
                }
            });
        });
    }

    // --- Independent Image Sliders Logic ---
    const cards = document.querySelectorAll('.deep-dive-card');

    cards.forEach(card => {
        const track = card.querySelector('.deep-dive-track');
        if (!track) return;

        const slides = Array.from(track.children);
        const nextBtn = card.querySelector('.next-dd-btn');
        const prevBtn = card.querySelector('.prev-dd-btn');

        let currentIndex = 0;

        const updateSlider = (index) => {
            if (index < 0) {
                index = slides.length - 1;
            } else if (index >= slides.length) {
                index = 0;
            }
            currentIndex = index;
            // Shift track to the left by (index * 100)%
            track.style.transform = `translateX(-${currentIndex * 100}%)`;
        };

        if (nextBtn && prevBtn) {
            nextBtn.addEventListener('click', () => updateSlider(currentIndex + 1));
            prevBtn.addEventListener('click', () => updateSlider(currentIndex - 1));
        }
    });

    // --- Smooth Scrolling for Navigation Links ---
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const targetId = this.getAttribute('href');
            if(targetId === '#') return;
            const targetElement = document.querySelector(targetId);
            if(targetElement) {
                targetElement.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });

    // --- Custom Glass Cursor Tracking ---
    const cursor = document.getElementById('custom-cursor');
    if (cursor) {
        document.addEventListener('mousemove', (e) => {
            cursor.style.left = e.clientX + 'px';
            cursor.style.top = e.clientY + 'px';
        });

        const interactables = document.querySelectorAll('a, button, label, .carousel-item');
        interactables.forEach(el => {
            el.addEventListener('mouseenter', () => cursor.classList.add('hovering'));
            el.addEventListener('mouseleave', () => cursor.classList.remove('hovering'));
        });
    }
});
